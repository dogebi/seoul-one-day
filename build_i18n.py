#!/usr/bin/env python3
"""Merge i18n/<lang>.json dictionaries with i18n/runtime.js into a single i18n.js bundle."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
LANGS = ["ko", "en", "ja", "zh"]

# Per-language value corrections that are not translations but units/scale.
OVERRIDES = {
    "en": {"stats.0.value": "14.54", "stats.0.unit": "M visitors", "stats.1.unit": "days"},
    "ja": {"stats.1.unit": "日"},
    "zh": {"stats.1.unit": "天"},
}

dicts = {}
for lang in LANGS:
    path = ROOT / "i18n" / f"{lang}.json"
    if not path.exists():
        raise SystemExit(f"missing {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    dicts[lang] = data

base_keys = set(dicts["ko"])
for lang, data in dicts.items():
    extra = set(data) - base_keys
    missing = base_keys - set(data)
    if extra or missing:
        raise SystemExit(f"{lang}: extra={sorted(extra)[:5]} missing={sorted(missing)[:5]}")
    empty = [k for k, v in data.items() if not str(v).strip()]
    if empty:
        raise SystemExit(f"{lang}: empty values {empty[:5]}")

# Scale/unit corrections are language-specific additions, applied after the key check.
for lang, overrides in OVERRIDES.items():
    dicts[lang].update(overrides)

runtime = (ROOT / "i18n" / "runtime.js").read_text(encoding="utf-8")
bundle = (
    "/* Generated by build_i18n.py — edit i18n/<lang>.json, not this file. */\n"
    "window.SEOUL_DICT = "
    + json.dumps(dicts, ensure_ascii=False, indent=1)
    + ";\n\n"
    + runtime
)
(ROOT / "i18n.js").write_text(bundle, encoding="utf-8")
print(f"wrote i18n.js — {len(base_keys)} keys x {len(LANGS)} languages, {len(bundle.encode())} bytes")
